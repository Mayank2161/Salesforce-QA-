import { createRequire } from "node:module";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
const req = createRequire(createRequire(import.meta.url).resolve("@playwright/mcp"));
const { createConnection } = req("@playwright/mcp");
const { chromium } = req("playwright-core");
const browser = await chromium.launch({ channel: "chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const server = await createConnection({ browser: { isolated: false }, codegen: "none" }, async () => context);
const [a, b] = InMemoryTransport.createLinkedPair();
await server.connect(a);
const client = new Client({ name: "proxy", version: "1" });
await client.connect(b);
const tools = await client.listTools();
console.log(tools.tools.map((t) => t.name).join(","));
const r = await client.callTool({ name: "browser_navigate", arguments: { url: "data:text/html,<label>Name<input id=n></label><button>Save</button>" } });
console.log(JSON.stringify(r).slice(0, 600));
const page = context.pages()[0];
await page.getByLabel("Name").fill("hello");
const s = await client.callTool({ name: "browser_snapshot", arguments: {} });
console.log(JSON.stringify(s).slice(0, 800));
const snap = JSON.stringify(s); const ref = /\[ref=(e\d+)\]/.exec(snap.replace(/\n/g,"\n"))?.[1]; console.log("ref", ref);
console.log("aria-ref count", await page.locator(`aria-ref=${ref}`).count());
await browser.close(); process.exit(0);
